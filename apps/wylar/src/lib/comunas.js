export function normalizeSearch(text) {
    return text ? text.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim() : '';
}

export function searchComunas(query) {
    if (!query || !query.trim()) return COMUNAS;
    const q = normalizeSearch(query);
    return COMUNAS.filter((c) => normalizeSearch(c.name).includes(q) || normalizeSearch(c.region).includes(q));
}
